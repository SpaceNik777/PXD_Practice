-- Идентификаторы проектов детерминированы:
--   '11000000-0000-0000-0000-00000000000k', где k — hex-цифры 2..a (k=2..10).
-- Идентификаторы задач детерминированы префиксом 'a<k>':
--   'a<kbd>00000-0000-0000-0000-' || lpad(g, 12, '0').
-- created_at отсчитывается от фиксированной даты с шагом в секунду.
-- Сценарий полностью повторяем после пересоздания тома с данными.
-- Итог: у Alpha 10 проектов x 10 000 задач = 100 000, у Beta 10 000.

INSERT INTO projects (tenant_id, id, name)
SELECT
    '10000000-0000-0000-0000-000000000001'::uuid,
    ('11000000-0000-0000-0000-00000000000' || p)::uuid,
    'Alpha Project ' || p
FROM (VALUES ('2'), ('3'), ('4'), ('5'), ('6'), ('7'), ('8'), ('9'), ('a')) AS v(p);


INSERT INTO tasks (tenant_id, id, project_id, title, status, created_at)
SELECT
    '10000000-0000-0000-0000-000000000001'::uuid,
    ('a' || v.p || '000000-0000-0000-0000-' || lpad(g::text, 12, '0'))::uuid,
    ('11000000-0000-0000-0000-00000000000' || v.p)::uuid,
    'Alpha task ' || v.p || ' ' || g,
    CASE WHEN g % 4 = 0 THEN 'done' ELSE 'open' END,
    timestamptz '2026-09-01 00:00:00+00' - make_interval(secs => 10000 - g)
FROM generate_series(1, 10000) AS g
CROSS JOIN (VALUES ('2'), ('3'), ('4'), ('5'), ('6'), ('7'), ('8'), ('9'), ('a')) AS v(p);


